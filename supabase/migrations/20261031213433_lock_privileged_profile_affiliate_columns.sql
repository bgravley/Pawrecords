-- Security hotfix: an authenticated user's own-row RLS policy does NOT prevent
-- updates to privileged columns on that row. Stop client-side privilege,
-- billing and commission changes at the database GRANT level.
--
-- Requires the matching app release:
--   - account referrals use POST /api/apply-referral
--   - every admin API authorizes against server-managed profiles.is_admin
--   - profile editing writes only the allowlisted personal-information columns
--
-- No customer rows are modified. Never apply independently of the app release
-- or without the separately approved production deployment window.

begin;

-- Separate owner SELECT / UPDATE policies. Ordinary customers never need to
-- create, replace or delete their profile row directly: signup uses a trusted
-- database trigger and account deletion is a server-authenticated workflow.
drop policy if exists "own profile" on public.profiles;
drop policy if exists "profiles owner select" on public.profiles;
drop policy if exists "profiles owner update" on public.profiles;

create policy "profiles owner select" on public.profiles
  for select to authenticated
  using ((select auth.uid()) = id);

create policy "profiles owner update" on public.profiles
  for update to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

-- A table-level UPDATE grant overrides any column-level restrictions; revoke
-- it first, including all legacy automatic grants. Protected fields (is_admin,
-- email, subscription_tier, Stripe IDs, referral code, AI limits and credits)
-- remain writable only by privileged server-side operations.
revoke all privileges on table public.profiles from public, anon, authenticated;
grant select on table public.profiles to authenticated;
grant update (
  full_name, phone, phone_country_code, whatsapp, whatsapp_country_code,
  address, city, state, zip, country, instagram, facebook, twitter,
  photo_url, avatar_url, email_notifications
) on table public.profiles to authenticated;

-- Affiliates can view their own record and adjust where they receive payouts,
-- but commission rate, status, referral code and ownership are server-only.
-- Existing owner-based RLS policies remain in force.
revoke all privileges on table public.affiliates from public, anon, authenticated;
grant select on table public.affiliates to authenticated;
grant update (payout_paypal, payout_stripe_email)
  on table public.affiliates to authenticated;

-- Commissions are accounting records generated by signed Stripe events.
-- Affiliates may read their own rows through existing owner-based RLS only.
revoke all privileges on table public.affiliate_commissions from public, anon, authenticated;
grant select on table public.affiliate_commissions to authenticated;

commit;
